PROMPT >>> SECTION 13: PL/SQL EXPLICIT CURSORS & ATTRIBUTES

DECLARE
    CURSOR c_low_stock IS
        SELECT medicine_name, quantity, reorder_threshold
        FROM MEDICINE
        WHERE quantity <= reorder_threshold
        ORDER BY quantity ASC;

    v_name      MEDICINE.medicine_name%TYPE;
    v_qty       MEDICINE.quantity%TYPE;
    v_threshold MEDICINE.reorder_threshold%TYPE;
    v_counter   NUMBER := 0;
BEGIN
    OPEN c_low_stock;
    DBMS_OUTPUT.PUT_LINE('=== REORDER NOTIFICATION MANIFEST ===');
    LOOP
        FETCH c_low_stock INTO v_name, v_qty, v_threshold;
        EXIT WHEN c_low_stock%NOTFOUND;
        
        v_counter := v_counter + 1;
        DBMS_OUTPUT.PUT_LINE(
            '[' || v_counter || '] ' || RPAD(v_name, 22) || 
            ' Current: ' || LPAD(TO_CHAR(v_qty), 4) || 
            ' | Minimum Threshold: ' || v_threshold
        );
    END LOOP;
    CLOSE c_low_stock;

    IF v_counter = 0 THEN
        DBMS_OUTPUT.PUT_LINE('>> No medicines currently under minimum reorder threshold.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('>> Total reorder requests dispatched: ' || v_counter);
    END IF;
END;
/

