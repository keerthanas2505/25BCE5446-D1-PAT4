DECLARE
    v_total_stock NUMBER := 0;
    v_med_count   NUMBER := 0;
    v_status      VARCHAR2(50);
BEGIN
    SELECT COUNT(*), NVL(SUM(quantity), 0)
    INTO v_med_count, v_total_stock
    FROM MEDICINE;

    -- Conditional Statement (IF - ELSIF - ELSE)
    IF v_total_stock = 0 THEN
        v_status := 'CRITICAL: Pharmacy completely depleted!';
    ELSIF v_total_stock < 200 THEN
        v_status := 'WARNING: Low overall pharmacy reserve.';
    ELSE
        v_status := 'OPTIMAL: Stock capacity healthy.';
    END IF;

    DBMS_OUTPUT.PUT_LINE('>> Formulations Count: ' || v_med_count);
    DBMS_OUTPUT.PUT_LINE('>> Total Physical Units: ' || v_total_stock);
    DBMS_OUTPUT.PUT_LINE('>> System Evaluation: ' || v_status);

    -- FOR LOOP demonstration iterating over top 3 expensive medicines
    DBMS_OUTPUT.PUT_LINE('--- Top Formulations By Price ---');
    FOR r IN (
        SELECT medicine_name, unit_price 
        FROM MEDICINE 
        ORDER BY unit_price DESC 
        FETCH FIRST 3 ROWS ONLY
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Drug: ' || RPAD(r.medicine_name, 25) || ' Price: INR ' || r.unit_price);
    END LOOP;
END;
