-- 14.1 Stored Function: Calculate Total Bill Amount given subtotal, discount, and tax
CREATE OR REPLACE FUNCTION FN_CALCULATE_FINAL_BILL (
    p_subtotal     IN NUMBER,
    p_discount_pct IN NUMBER,
    p_tax_pct      IN NUMBER
) RETURN NUMBER IS
    v_discounted NUMBER;
    v_final      NUMBER;
BEGIN
    v_discounted := p_subtotal - (p_subtotal * (NVL(p_discount_pct, 0) / 100.0));
    v_final      := v_discounted + (v_discounted * (NVL(p_tax_pct, 0) / 100.0));
    RETURN ROUND(v_final, 2);
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0.00;
END;
/

