CREATE OR REPLACE TRIGGER TRG_MEDICINE_STOCK_CHANGE
AFTER UPDATE OF quantity ON MEDICINE
FOR EACH ROW
BEGIN
    IF :NEW.quantity != :OLD.quantity THEN
        INSERT INTO MEDICINE_AUDIT_LOG (
            medicine_id,
            action_type,
            old_quantity,
            new_quantity,
            remarks
        ) VALUES (
            :NEW.medicine_id,
            CASE 
                WHEN :NEW.quantity < :OLD.quantity THEN 'SALE_DISPENSE'
                ELSE 'STOCK_IN'
            END,
            :OLD.quantity,
            :NEW.quantity,
            'Automated Oracle trigger audit log upon quantity modification'
        );
    END IF;
END;
