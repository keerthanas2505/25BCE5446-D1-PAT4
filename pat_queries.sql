-- 14.2 Stored Procedure: Replenish Medicine Stock
CREATE OR REPLACE PROCEDURE SP_RESTOCK_MEDICINE (
    p_medicine_id IN NUMBER,
    p_units_to_add IN NUMBER,
    p_status_msg  OUT VARCHAR2
) IS
    v_curr_stock NUMBER;
BEGIN
    IF p_units_to_add <= 0 THEN
        p_status_msg := 'ERROR: Restock quantity must be positive.';
        RETURN;
    END IF;

    SELECT quantity INTO v_curr_stock FROM MEDICINE WHERE medicine_id = p_medicine_id;

    UPDATE MEDICINE
    SET quantity = quantity + p_units_to_add
    WHERE medicine_id = p_medicine_id;

    COMMIT;
    p_status_msg := 'SUCCESS: Restocked ' || p_units_to_add || ' units. New total: ' || (v_curr_stock + p_units_to_add);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_status_msg := 'ERROR: Medicine ID not found.';
    WHEN OTHERS THEN
        p_status_msg := 'ERROR: Procedure failed - ' || SQLERRM;
END;
/

